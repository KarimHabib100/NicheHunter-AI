/**
 * Generate CSV export for data analysis
 */
export function generateExportCSV(analyses: FormattedAnalysis[]): string {
  const headers = [
    'Video Title',
    'Duration',
    'Grade',
    'Overall Score',
    'Hook Type',
    'Hook Score',
    'Retention Score',
    'Framework',
    'Structure Score',
    'Persona',
    'Persona Score',
    'Top Platform',
    'Platform Score',
    'Analyzed At',
  ];

  const rows = analyses.map((a) => [
    `"${a.meta.videoTitle.replace(/"/g, '""')}"`,
    a.meta.duration,
    a.meta.grade,
    a.meta.overallScore,
    a.sections.hook.type,
    a.sections.hook.score,
    a.sections.retention.score,
    a.sections.structure.framework,
    a.sections.structure.score,
    a.sections.persona.archetype,
    a.sections.persona.score,
    a.platforms[0]?.name || 'N/A',
    a.platforms[0]?.compatibility || 0,
    a.meta.analyzedAt,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
