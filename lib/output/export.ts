  lines.push('');
  lines.push(`🎬 ${analysis.meta.videoTitle}`);
  lines.push(`⏱️ Duration: ${analysis.meta.duration}`);
  lines.push('');
  lines.push(`🏆 Grade: ${analysis.meta.grade} (${analysis.meta.gradeLabel})`);
  lines.push(`📈 Score: ${analysis.meta.overallScore}%`);
  lines.push('');
  lines.push(`🎣 Hook: ${analysis.sections.hook.type} (${analysis.sections.hook.score}%)`);
  lines.push(`📐 Structure: ${analysis.sections.structure.framework}`);
  lines.push(`🎭 Persona: ${analysis.sections.persona.archetype}`);
  lines.push('');

  if (analysis.executive.keyStrengths.length > 0) {
    lines.push(`✅ Top Strength: ${analysis.executive.keyStrengths[0]}`);
  }

  if (analysis.executive.actionItems.length > 0) {
    lines.push(`💡 Quick Win: ${analysis.executive.actionItems[0]}`);
  }

  lines.push('');
  lines.push(`Analyze your content: nichehunter.ai`);

  return lines.join('\n');
